// Drafts a plain-text rent increase notice from an evaluation. The content
// follows what the SF Rent Board says a notice must state: the dollar amount,
// the percentage, and the effective date, served with the required lead time.

import { formatLong, type IsoDate } from './dates'
import type { Evaluation, ServiceMethod } from './engine'

export interface NoticeParties {
  landlordName: string
  tenantNames: string
  address: string
  serviceDate: IsoDate
  serviceMethod: ServiceMethod
}

const money = (n: number) =>
  n.toLocaleString('en-US', { style: 'currency', currency: 'USD', minimumFractionDigits: 2 })

export function draftNotice(ev: Evaluation, parties: NoticeParties): string {
  const increase = ev.proposedRent - ev.currentRent
  const lines: string[] = []
  lines.push('NOTICE OF CHANGE IN TERMS OF TENANCY: RENT INCREASE')
  lines.push('')
  lines.push(`To: ${parties.tenantNames || '[Tenant name(s)]'}, and all other occupants`)
  lines.push(`Premises: ${parties.address || '[Street address and unit], San Francisco, CA'}`)
  lines.push(`Date of notice: ${formatLong(parties.serviceDate)}`)
  lines.push('')
  lines.push(
    `Please take notice that, effective ${formatLong(ev.effectiveDate)}, your monthly rent will increase from ${money(ev.currentRent)} to ${money(ev.proposedRent)}.`,
  )
  lines.push(`This is an increase of ${money(increase)} per month, or ${ev.proposedPercent.toFixed(2)}%.`)
  lines.push('')

  if (ev.regime === 'sf_rent_ordinance') {
    lines.push('Basis for the increase (San Francisco Rent Ordinance, Admin. Code Chapter 37):')
    for (const b of ev.breakdown) lines.push(`  • ${b.label}: ${b.percent.toFixed(1)}%`)
    for (const y of ev.bankedYears) {
      lines.push(
        `      – ${y.source === 'partial' ? 'Unused portion of increase on' : 'Banked from anniversary'} ${y.anniversary}: ${y.percent.toFixed(1)}%`,
      )
    }
    lines.push('Banked increases are added together, not compounded, and applied to the current base rent.')
    lines.push('')
    lines.push(
      'Information about your rights is available from the San Francisco Rent Board at sf.gov/rentboard.',
    )
  } else if (ev.regime === 'ab1482') {
    lines.push(
      `This increase complies with California Civil Code §1947.12 (AB 1482), which limits increases over any 12 months to ${ev.maxPercent?.toFixed(1)}% for increases effective on this date in the San Francisco region.`,
    )
  } else {
    lines.push('This unit is not subject to local or state rent increase limits.')
  }

  lines.push('')
  lines.push(
    `This notice is given at least ${ev.notice.baseDays} days before the effective date, as required by California Civil Code §827${ev.notice.mailDays ? ', plus 5 days because it is served by mail (Code Civ. Proc. §1013)' : ''}.`,
  )
  lines.push('All other terms of your tenancy remain unchanged.')
  lines.push('')
  lines.push('______________________________')
  lines.push(parties.landlordName || '[Owner or agent name]')
  lines.push('')
  lines.push('PROOF OF SERVICE')
  lines.push(
    `I served this notice on ${formatLong(parties.serviceDate)} by ${parties.serviceMethod === 'mail' ? 'first-class mail, postage prepaid, addressed to the tenant(s) at the premises' : 'personal delivery to the tenant(s)'}.`,
  )
  lines.push('Signature: ______________________   Name: ______________________')
  lines.push('')
  lines.push('DRAFT generated by a demo tool. Not legal advice; have it reviewed before serving.')
  return lines.join('\n')
}
